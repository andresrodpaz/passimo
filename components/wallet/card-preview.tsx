import * as React from 'react'
import { MapPin, Sparkles } from 'lucide-react'
import { cn } from '@/lib/utils'
import { useI18n } from '@/lib/i18n'
import {
  cardBackground,
  fontStack,
  shift,
  type ResolvedCardDesign,
} from '@/lib/wallet/card-design'

/**
 * The loyalty card, as each wallet actually lays it out.
 *
 * Two renderers rather than one with a badge, because Apple and Google are not
 * the same product wearing different colours and a merchant deciding what their
 * customer will hold deserves to see the real difference:
 *
 *   * **Apple** paints the whole pass in the brand colour. Fields are stacked in
 *     labelled rows — header, primary, secondary, auxiliary — and the barcode
 *     sits in a white well at the bottom with the serial beneath it.
 *   * **Google** paints a brand-coloured *header* on a neutral surface. The
 *     balance is a large module, the logo is a circle, and the barcode is a wide
 *     white panel. The chrome around it is Google's, not the merchant's.
 *
 * Both consume `ResolvedCardDesign` — the same structure the pass builder uses —
 * so the preview cannot drift from what is generated. That was the whole reason
 * to resolve the design in an isomorphic module.
 *
 * These are previews, and the UI says so next to them. They are not generated by
 * Apple's or Google's SDK and must never be presented as though they were.
 */

export type CardPreviewData = {
  organizationName: string
  programName: string
  memberName: string | null
  memberSince: string | null
  tierName: string | null
  locationName: string | null
  balance: number
  goal: number | null
  unitSingular: string
  unitPlural: string
  rewardName: string | null
  /**
   * What the merchant's brand kit puts on the reverse.
   *
   * Optional because the landing page has no merchant. When present the back
   * shows exactly what a real pass carries there — both wallets render contact
   * details and small print on the reverse, and it is the only place the brand
   * kit's phone number, address and social handles reach a customer at all.
   */
  contact?: {
    description?: string | null
    website?: string | null
    phone?: string | null
    email?: string | null
    address?: string | null
    socials?: { instagram?: string | null; facebook?: string | null; tiktok?: string | null }
  }
}

export type CardPreviewProps = {
  platform: 'apple' | 'google'
  design: ResolvedCardDesign
  data: CardPreviewData
  /** Shows the reverse of the card — custom message, terms, contact. */
  showBack?: boolean
  /** Bumped on change so the balance can animate. */
  animateKey?: number
  className?: string
}

export function CardPreview({ platform, ...rest }: CardPreviewProps) {
  return platform === 'apple' ? <ApplePassPreview {...rest} /> : <GooglePassPreview {...rest} />
}

