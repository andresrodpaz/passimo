// Shared pieces
// -----------------------------------------------------------------------------

function useProgress(data: CardPreviewData) {
  const rewardReady = data.goal != null && data.goal > 0 && data.balance >= data.goal
  const remaining = data.goal != null ? Math.max(0, data.goal - data.balance) : null
  const ratio = data.goal && data.goal > 0 ? Math.min(1, data.balance / data.goal) : 0
  return { rewardReady, remaining, ratio }
}

/** Initials for the logo well when the merchant has not uploaded a logo yet. */
function initials(name: string): string {
  const words = name.trim().split(/\s+/).filter(Boolean)
  if (words.length === 0) return '?'
  if (words.length === 1) return words[0]!.slice(0, 2).toUpperCase()
  return `${words[0]![0]}${words[1]![0]}`.toUpperCase()
}

function LogoMark({
  design,
  name,
  className,
  style,
}: {
  design: ResolvedCardDesign
  name: string
  className?: string
  style?: React.CSSProperties
}) {
  if (design.logoUrl) {
    return (
      // A merchant's logo is arbitrary user content, so it is contained rather
      // than cropped — a wordmark cropped to a square is a broken brand.
      // eslint-disable-next-line @next/next/no-img-element
      <img
        src={design.logoUrl}
        alt=""
        className={cn('object-contain', className)}
        style={style}
        loading="lazy"
        decoding="async"
      />
    )
  }
  return (
    <span aria-hidden className={cn('flex items-center justify-center font-bold', className)} style={style}>
      {initials(name)}
    </span>
  )
}

/**
 * The hero/strip image.
 *
 * Apple embeds this as `strip.png` and Google as `heroImage`, and both were
 * already consuming `design.heroImageUrl` — but nothing rendered it, so a
 * merchant had no way to see what they were shipping. Rendered as a band because
 * that is where both platforms place it: full width, fixed aspect, cropped.
 *
 * `<img>` rather than `next/image` deliberately: the source is a merchant URL on
 * an arbitrary host, and the optimiser is disabled for this deployment anyway.
 */
function HeroStrip({ url, className }: { url: string; className?: string }) {
  return (
    /* eslint-disable-next-line @next/next/no-img-element */
    <img
      src={url}
      alt=""
      aria-hidden
      className={cn('h-16 w-full object-cover', className)}
      loading="lazy"
    />
  )
}

/**
 * A stamp grid.
 *
 * Wraps at six per row, which is what keeps a ten-stamp card readable at card
 * width. `card-design.ts` refuses to choose this style above twelve stamps.
 */
function Stamps({
  filled,
  total,
  accent,
  foreground,
}: {
  filled: number
  total: number
  accent: string
  foreground: string
}) {
  const cells = Array.from({ length: Math.max(0, total) })
  return (
    <div className="flex flex-wrap gap-1.5" role="img" aria-label={`${filled} / ${total}`}>
      {cells.map((_, index) => {
        const isFilled = index < filled
        return (
          <span
            key={index}
            aria-hidden
            className="size-5 rounded-full border-2 transition-colors duration-300"
            style={{
              borderColor: isFilled ? accent : `${foreground}59`,
              backgroundColor: isFilled ? accent : 'transparent',
            }}
          />
        )
      })}
    </div>
  )
}

function ProgressBar({
  ratio,
  accent,
  track,
  label,
}: {
  ratio: number
  accent: string
  track: string
  label: string
}) {
  return (
    <div
      className="h-2 overflow-hidden rounded-full"
      style={{ backgroundColor: track }}
      role="progressbar"
      aria-valuenow={Math.round(ratio * 100)}
      aria-valuemin={0}
      aria-valuemax={100}
      aria-label={label}
    >
      <div
        className="h-full rounded-full transition-[width] duration-700 ease-out motion-reduce:transition-none"
        style={{ width: `${ratio * 100}%`, backgroundColor: accent }}
      />
    </div>
  )
}

/**
 * A deterministic QR-looking pattern.
 *
 * Not a real QR code: a preview has nothing to encode, and a scannable code that
 * resolves to nothing is worse than an obvious placeholder. Seeded rather than
 * random so the server and client render identical markup — `Math.random()` here
 * is a hydration mismatch on every load.
 */
function QrPattern({ className, dark = '#111827' }: { className?: string; dark?: string }) {
  const cells = React.useMemo(() => {
    const size = 21
    const grid: boolean[] = []
    let state = 0x2f6e2b1
    for (let index = 0; index < size * size; index += 1) {
      state = (state * 1103515245 + 12345) & 0x7fffffff
      grid.push(((state >> 16) & 1) === 1)
    }
    const finder = (row: number, col: number) => {
      for (let r = 0; r < 7; r += 1) {
        for (let c = 0; c < 7; c += 1) {
          const edge = r === 0 || r === 6 || c === 0 || c === 6
          const core = r >= 2 && r <= 4 && c >= 2 && c <= 4
          grid[(row + r) * size + (col + c)] = edge || core
        }
      }
    }
    finder(0, 0)
    finder(0, size - 7)
    finder(size - 7, 0)
    return grid
  }, [])

  return (
    <div
      aria-hidden
      className={cn('grid', className)}
      style={{ gridTemplateColumns: 'repeat(21, minmax(0, 1fr))' }}
    >
      {cells.map((filled, index) => (
        <span key={index} style={{ backgroundColor: filled ? dark : 'transparent' }} />
      ))}
    </div>
  )
}

/** A labelled field, the unit Apple lays a pass out in. */
function Field({
  label,
  children,
  align = 'left',
  labelColor,
  className,
}: {
  label: string
  children: React.ReactNode
  align?: 'left' | 'right'
  labelColor: string
  className?: string
}) {
  return (
    <div className={cn('min-w-0', align === 'right' && 'text-right', className)}>
      <p
        className="truncate text-[9px] font-semibold uppercase tracking-[0.14em]"
        style={{ color: labelColor }}
      >
        {label}
      </p>
      <div className="mt-0.5 truncate text-sm font-medium">{children}</div>
    </div>
  )
}

