/**
 * The reverse — where both wallets put contact details and small print.
 *
 * Worth previewing because it is the only place a merchant's own words reach the
 * customer unprompted, and the only place the brand kit's contact fields surface
 * on the card at all.
 */
function CardBack({
  design,
  data,
  platform,
  className,
}: {
  design: ResolvedCardDesign
  data: CardPreviewData
  platform: 'apple' | 'google'
  className?: string
}) {
  const { t } = useI18n()
  const isApple = platform === 'apple'
  const contact = data.contact ?? {}

  const rows = [
    { label: t('brandKit.website'), value: contact.website },
    { label: t('brandKit.phone'), value: contact.phone },
    { label: t('brandKit.email'), value: contact.email },
    { label: t('brandKit.address'), value: contact.address },
  ].filter((row): row is { label: string; value: string } => Boolean(row.value))

  const socials = [
    contact.socials?.instagram,
    contact.socials?.facebook,
    contact.socials?.tiktok,
  ].filter((handle): handle is string => Boolean(handle))

  /*
   * "Empty" means the merchant has given the back nothing of their own. The
   * business name alone does not count — it is on the front too, so a back
   * showing only that is the state the hint is meant to prompt them out of.
   */
  const isEmpty =
    !design.customMessage &&
    !design.termsText &&
    !contact.description &&
    rows.length === 0 &&
    socials.length === 0

  return (
    <div
      className={cn(
        'w-full max-w-[340px] overflow-hidden rounded-[1.25rem] shadow-2xl ring-1 ring-black/10',
        isApple ? '' : 'bg-white dark:bg-neutral-900',
        className
      )}
      style={
        isApple
          ? {
              background: shift(design.backgroundColor, -0.15),
              color: design.foregroundColor,
              fontFamily: fontStack(design.typography),
            }
          : { fontFamily: fontStack(design.typography) }
      }
    >
      <div className="space-y-4 p-4 text-[12px] leading-relaxed">
        <p className="text-[10px] font-semibold uppercase tracking-[0.14em] opacity-60">
          {t('cardDesign.back.title')}
        </p>

        {design.customMessage && <p className="font-medium">{design.customMessage}</p>}

        <div className="space-y-1.5 opacity-80">
          <p className="font-semibold">{data.organizationName}</p>
          {contact.description && <p className="opacity-80">{contact.description}</p>}

          {/* Contact rows. Plain text rather than links: this is a picture of a
              pass, and a live `tel:` here would dial the merchant's own phone
              from the merchant's own dashboard the first time they tapped it. */}
          <dl className="space-y-1 pt-1">
            {rows.map((row) => (
              <div key={row.label} className="flex gap-2">
                <dt className="shrink-0 opacity-60">{row.label}</dt>
                <dd className="min-w-0 flex-1 truncate">{row.value}</dd>
              </div>
            ))}
          </dl>

          {socials.length > 0 && (
            <p className="flex flex-wrap gap-x-3 gap-y-1 pt-1 opacity-70">
              {socials.map((social) => (
                <span key={social}>@{social}</span>
              ))}
            </p>
          )}
        </div>

        {design.termsText && (
          <div className="border-t border-current/15 pt-3">
            <p className="text-[10px] opacity-60">{design.termsText}</p>
          </div>
        )}

        {isEmpty && <p className="opacity-60">{t('cardDesign.back.empty')}</p>}
      </div>
    </div>
  )
}
