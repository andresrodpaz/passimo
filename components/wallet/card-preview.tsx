// Apple
// -----------------------------------------------------------------------------

export function ApplePassPreview({
  design,
  data,
  showBack = false,
  animateKey,
  className,
}: Omit<CardPreviewProps, 'platform'>) {
  const { t, formatNumber } = useI18n()
  const { rewardReady, remaining, ratio } = useProgress(data)

  const fg = design.foregroundColor
  const label = `${fg}b3`
  const surface = cardBackground(design)

  if (showBack) {
    return <CardBack design={design} data={data} className={className} platform="apple" />
  }

  return (
    <div
      className={cn(
        'relative w-full max-w-[340px] overflow-hidden rounded-[1.25rem] shadow-2xl ring-1 ring-black/10',
        className
      )}
      style={{ background: surface, color: fg, fontFamily: fontStack(design.typography) }}
    >
      {/* Apple's passes carry a soft top light; without it a flat hex reads as a div. */}
      <div
        aria-hidden
        className="pointer-events-none absolute inset-0 bg-gradient-to-b from-white/12 via-transparent to-black/20"
      />

      <div className="relative p-4">
        {/* Header row — logo, logoText, one header field. */}
        <header className="flex items-center gap-2.5">
          <LogoMark
            design={design}
            name={data.organizationName}
            className="size-8 shrink-0 rounded-lg text-[11px]"
            style={{ backgroundColor: design.logoUrl ? 'transparent' : `${fg}26`, color: fg }}
          />
          <p className="min-w-0 flex-1 truncate text-[13px] font-semibold">
            {design.headline ?? data.organizationName}
          </p>
          {design.showTier && data.tierName && (
            <Field label={t('wallet.preview.tier')} align="right" labelColor={label}>
              {data.tierName}
            </Field>
          )}
        </header>

        {/* Apple places `strip.png` directly beneath the header. */}
        {design.heroImageUrl && (
          <HeroStrip url={design.heroImageUrl} className="mt-3 rounded-lg" />
        )}

        {/* Primary field — the number the customer opens the card to see. */}
        {design.showProgress && design.effectiveProgress !== 'none' && (
          <div className="mt-5">
            <p
              className="text-[9px] font-semibold uppercase tracking-[0.14em]"
              style={{ color: label }}
            >
              {data.unitPlural}
            </p>

            {design.effectiveProgress === 'stamps' && data.goal ? (
              <div className="mt-2">
                <Stamps
                  filled={data.balance}
                  total={data.goal}
                  accent={design.accentColor}
                  foreground={fg}
                />
              </div>
            ) : (
              <p
                key={animateKey}
                className="mt-0.5 text-[2.6rem] font-bold leading-none tabular-nums motion-safe:animate-in motion-safe:zoom-in-95 motion-safe:duration-300"
              >
                {formatNumber(data.balance)}
                {data.goal != null && data.goal > 0 && design.effectiveProgress !== 'points' && (
                  <span className="text-xl font-medium" style={{ color: label }}>
                    {' / '}
                    {formatNumber(data.goal)}
                  </span>
                )}
              </p>
            )}

            {design.effectiveProgress === 'bar' && data.goal != null && data.goal > 0 && (
              <div className="mt-3">
                <ProgressBar
                  ratio={ratio}
                  accent={design.accentColor}
                  track={`${fg}2e`}
                  label={data.unitPlural}
                />
              </div>
            )}
          </div>
        )}

        {/* Secondary field — the reward. */}
        {design.showReward && (
          <div className="mt-5">
            <p
              className="flex items-center gap-1 text-[9px] font-semibold uppercase tracking-[0.14em]"
              style={{ color: rewardReady ? design.accentColor : label }}
            >
              {rewardReady && <Sparkles className="size-3" aria-hidden />}
              {rewardReady ? t('card.rewardReady') : t('wallet.preview.reward')}
            </p>
            <p className="mt-0.5 text-sm font-medium leading-snug">
              {data.rewardName ?? t('wallet.preview.reward')}
            </p>
            {!rewardReady && remaining !== null && remaining > 0 && (
              <p className="mt-0.5 text-[11px]" style={{ color: label }}>
                {t('card.toGo', { count: remaining })}
              </p>
            )}
          </div>
        )}

        {/* Auxiliary fields. */}
        {(design.showMemberName || design.showMemberSince || design.showLocation) && (
          <div className="mt-5 flex items-end justify-between gap-3">
            <div className="min-w-0 space-y-1">
              {design.showMemberName && data.memberName && (
                <Field label={t('wallet.preview.member')} labelColor={label}>
                  {data.memberName}
                </Field>
              )}
              {design.showLocation && data.locationName && (
                <p className="flex items-center gap-1 truncate text-[11px]" style={{ color: label }}>
                  <MapPin className="size-3 shrink-0" aria-hidden />
                  {data.locationName}
                </p>
              )}
            </div>
            {design.showMemberSince && data.memberSince && (
              <Field label={t('wallet.preview.memberSince')} align="right" labelColor={label}>
                {data.memberSince}
              </Field>
            )}
          </div>
        )}
      </div>

      {/* The barcode well. Apple renders it on white regardless of the pass
          colour, because scanners need the contrast. */}
      <div className="relative px-4 pb-4">
        <div className="flex flex-col items-center gap-1.5 rounded-xl bg-white p-3">
          <QrPattern className="size-24" />
          <p className="text-[9px] font-medium tracking-wide text-neutral-500">
            {t('wallet.preview.showQr')}
          </p>
        </div>
      </div>
    </div>
  )
}

